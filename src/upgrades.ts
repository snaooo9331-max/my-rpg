// =====================================================
// upgrades.ts
// 強化ポイントで上げられる能力（メニューの「つよさ」）をまとめたファイル
//   使っている場所：menu.ts（つよさ画面）
//   ※ バトルの技（スキル）は、あとで skills.ts に作る予定
// =====================================================

// -----------------------------------------------------
// StatName … 上げられる能力の名前
//   player の項目名（attack / defense / maxHp）とそろえている
//   → menu.ts で player[stat] と書くと、その項目を直接増やせる
// -----------------------------------------------------
export type StatName = "attack" | "defense" | "maxHp";

// -----------------------------------------------------
// StatUpgrade … 能力の上げ方1つ分のデータの「形」
// -----------------------------------------------------
export type StatUpgrade = {
  id: string;        // プログラムの中で使う名前（ボタンの data-id に入る）
  name: string;      // 画面に出す名前（ちから・まもり・たいりょく）
  stat: StatName;    // どの能力を上げるか
  amount: number;    // 強化ポイント1つで上がる量
};

// -----------------------------------------------------
// STAT_LABELS … 能力の名前 → 画面に出す名前（対応表）
//   Record<StatName, …> なので、能力を増やして書き忘れると赤線で教えてくれる
// -----------------------------------------------------
export const STAT_LABELS: Record<StatName, string> = {
  attack: "攻撃力",
  defense: "守備力",
  maxHp: "最大HP",
};

// -----------------------------------------------------
// STAT_UPGRADES … 能力の上げ方の一覧（データ）
//   つよさ画面には、この順番で並ぶ
//   上がる量を変えたいときは amount を変えるだけ
// -----------------------------------------------------
export const STAT_UPGRADES: StatUpgrade[] = [
  { id: "power", name: "ちから", stat: "attack", amount: 1 },
  { id: "guard", name: "まもり", stat: "defense", amount: 1 },
  { id: "vitality", name: "たいりょく", stat: "maxHp", amount: 5 },
];
